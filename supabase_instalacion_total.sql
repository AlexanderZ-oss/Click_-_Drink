-- 1. EXTENSIONES
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. TABLA PROFILES (usuarios y admin)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  email TEXT UNIQUE,
  full_name TEXT,
  phone TEXT,
  role TEXT DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- 3. TABLA PRODUCTS
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  name TEXT NOT NULL,
  description TEXT,
  price NUMERIC NOT NULL,
  category TEXT,
  image_url TEXT,
  stock INTEGER DEFAULT 0,
  active BOOLEAN DEFAULT true,
  wholesale_price NUMERIC(10,2),
  wholesale_min INTEGER DEFAULT 12
);

-- 4. TABLA ORDERS (pedidos; columnas completas del checkout)
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  user_id UUID REFERENCES auth.users,
  customer_name TEXT,
  customer_email TEXT,
  customer_phone TEXT,
  total NUMERIC NOT NULL,
  status TEXT DEFAULT 'pending',
  items JSONB,
  invoice_type TEXT DEFAULT 'boleta',
  ruc_dni TEXT,
  company_name TEXT,
  delivery_address TEXT,
  delivery_time TEXT,
  delivery_fee NUMERIC DEFAULT 0,
  payment_method_id BIGINT,
  notes TEXT,
  paid_at TIMESTAMPTZ
);

-- 5. TABLA ORDER_ITEMS (detalle por producto)
CREATE TABLE IF NOT EXISTS public.order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id BIGINT,
  product_name TEXT,
  quantity INTEGER DEFAULT 1,
  price NUMERIC(10,2),
  subtotal NUMERIC(10,2),
  options JSONB
);

-- 6. TABLA BANNERS (anuncios)
CREATE TABLE IF NOT EXISTS public.banners (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  title TEXT NOT NULL,
  description TEXT,
  image_url TEXT,
  link_url TEXT,
  active BOOLEAN DEFAULT true,
  display_order INTEGER DEFAULT 0,
  background_color TEXT DEFAULT '#050505',
  text_color TEXT DEFAULT '#FFFFFF',
  start_date TIMESTAMPTZ,
  end_date TIMESTAMPTZ
);

-- 7. TABLA PROMOTIONS
CREATE TABLE IF NOT EXISTS public.promotions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  title TEXT NOT NULL,
  description TEXT,
  discount_percent NUMERIC,
  image_url TEXT,
  active BOOLEAN DEFAULT true,
  valid_until TIMESTAMPTZ
);

-- 8. TABLA MESSAGES (contacto)
CREATE TABLE IF NOT EXISTS public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  name TEXT,
  email TEXT,
  subject TEXT,
  message TEXT,
  phone TEXT,
  read BOOLEAN DEFAULT false
);

-- 9. TABLA EVENTS
CREATE TABLE IF NOT EXISTS public.events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  title TEXT NOT NULL,
  description TEXT,
  date TIMESTAMPTZ NOT NULL,
  location TEXT DEFAULT 'Trujillo',
  image_url TEXT,
  price NUMERIC(10,2) DEFAULT 0,
  active BOOLEAN DEFAULT true,
  ticket_link TEXT
);

-- 10. TABLA REVIEWS
CREATE TABLE IF NOT EXISTS public.reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  user_id UUID REFERENCES auth.users NOT NULL,
  user_name TEXT,
  user_avatar TEXT,
  rating INTEGER CHECK (rating >= 1 AND rating <= 5),
  comment TEXT,
  product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE
);

-- 11. TABLA ANALYTICS
CREATE TABLE IF NOT EXISTS public.analytics (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date DATE DEFAULT CURRENT_DATE UNIQUE,
  page_views INTEGER DEFAULT 0,
  orders_count INTEGER DEFAULT 0,
